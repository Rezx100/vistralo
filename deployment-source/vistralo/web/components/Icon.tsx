export type IconName = keyof typeof paths;
type IconProps = React.SVGProps<SVGSVGElement> & {
  name: IconName | string;
  size?: number;
};
const directional = new Set([
  "chevronRight",
  "arrowLeft",
  "arrowRight",
  "sidebar",
]);

export function Icon({ name, size = 20, className = "", ...props }: IconProps) {
  // Empty menu slots retain alignment without implying a document action.
  const variants = paths[name];
  if (name === "blank" || !variants)
    return (
      <svg
        width={size}
        height={size}
        viewBox={`0 0 ${size} ${size}`}
        aria-hidden="true"
        focusable="false"
        className={`icon icon-blank ${className}`.trim()}
        {...props}
      />
    );
  const nativeSize = variants[size]
    ? size
    : variants[20]
      ? 20
      : Number(Object.keys(variants)[0]);
  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${nativeSize} ${nativeSize}`}
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
      className={`icon ${directional.has(name) ? "icon-directional directional" : ""} ${className}`.trim()}
      {...props}
    >
      {variants[nativeSize].map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}
export default Icon;
